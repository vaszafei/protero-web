import { getSupabase } from '~/server/utils/supabase'

export default defineEventHandler(async (event) => {
  const { season, league } = getQuery(event)
  
  const targetSeason = season || '2025-2026'
  const supabase = getSupabase()
  
  try {
    console.log(`\n🔄 Bulk v2.0 regeneration for ${targetSeason}...`)
    
    // Build query based on parameters
    let whereClause = `
      WHERE g.season = ?
        AND g.status NOT IN ('cancelled', 'postponed')
        AND g.odds_home IS NOT NULL
        AND g.odds_draw IS NOT NULL
        AND g.odds_away IS NOT NULL
        AND p.id IS NULL
    `
    const args = [targetSeason]
    
    if (league) {
      whereClause += ` AND g.league_key = ?`
      args.push(league)
    }
    
    // Get games needing v2.0 predictions
    let query = supabase
      .from('games')
      .select(`
        *,
        home_team:teams!home_team_id(name),
        away_team:teams!away_team_id(name),
        predictions!left(id)
      `)
      .is('predictions.id', null)
      .not('status', 'in', '("cancelled","postponed")')
      .order('date', { ascending: true })
    
    if (league) {
      query = query.eq('league_key', league)
    }
    
    const { data: games, error } = await query
    
    if (error) {
      throw createError({ statusCode: 500, message: error.message })
    }
    console.log(`📊 Found ${games.length} games needing v2.0 predictions`)
    
    if (games.length === 0) {
      return {
        success: true,
        message: 'All games already have v2.0 predictions',
        generated: 0,
        total: 0
      }
    }
    
    // Predictions now generated by Python ML pipeline
    throw createError({ 
      statusCode: 501,
      statusMessage: 'Predictions Generated by Python Pipeline',
      message: `Use Python ML pipeline for bulk predictions: python ml/prediction/predict_v11_simple.py (${games.length} games available)`
    })
    
  } catch (error) {
    console.error('❌ Bulk regeneration error:', error)
    throw createError({
      statusCode: 500,
      message: 'Bulk regeneration failed: ' + error.message
    })
  }
})
